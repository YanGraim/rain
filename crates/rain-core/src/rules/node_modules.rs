        Metadata {
            is_dir,
            is_symlink: false,
            dev: 1,
            ino,
            nlink: if is_dir { 2 } else { 1 },
            blocks: if is_dir { 0 } else { 8 },
            len: if is_dir { 0 } else { 4096 },
            mtime: now() - Duration::from_secs(days * DAY),
        }
