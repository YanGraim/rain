    const HOME: &str = "/Users/Tester";
    const DAY: u64 = 86_400;
    const FIXTURE: &str = include_str!("../../tests/fixtures/dev_node_modules.txt");

    struct HomeAt;

    impl Platform for HomeAt {
        fn resolve(&self, _: Root) -> Result<PathBuf, PlatformError> {
            Ok(PathBuf::from(HOME))
        }
        fn is_root_user(&self) -> bool {
            false
        }
        fn os(&self) -> Os {
            Os::Macos
        }
    }

    fn now() -> SystemTime {
        SystemTime::UNIX_EPOCH + Duration::from_secs(1_000 * DAY)
    }

    fn aged(is_dir: bool, ino: u64, days: u64) -> Metadata {
        Metadata {
            is_dir,
            is_symlink: false,
            dev: 1,
            ino,
            nlink: if is_dir { 2 } else { 1 },
            blocks: if is_dir { 0 } else { 8 },
            len: if is_dir { 0 } else { 4096 },
            mtime: now() - Duration::from_secs(days * DAY),
        }
    }

    fn h(rel: &str) -> PathBuf {
        Path::new(HOME).join(rel)
    }

    /// Home on dev 1 plus the given `(kind, age, rel)` entries.
    struct Tree {
        fs: FakeFs,
        next_ino: u64,
    }

    impl Tree {
        fn new() -> Self {
            let mut fs = FakeFs::new();
            fs.insert("/Users", aged(true, 1, 900))
                .insert(HOME, aged(true, 2, 900));
            Tree { fs, next_ino: 10 }
        }

        fn add(&mut self, is_dir: bool, days: u64, rel: &str) -> &mut Self {
            self.next_ino += 1;
            self.fs.insert(h(rel), aged(is_dir, self.next_ino, days));
            self
        }

        fn d(&mut self, days: u64, rel: &str) -> &mut Self {
            self.add(true, days, rel)
        }

        fn f(&mut self, days: u64, rel: &str) -> &mut Self {
            self.add(false, days, rel)
        }

        fn fixture() -> Self {
            let mut t = Tree::new();
            for line in FIXTURE.lines() {
                let line = line.trim();
                if line.is_empty() || line.starts_with('#') {
                    continue;
                }
                let mut parts = line.splitn(3, ' ');
                let (kind, days, rel) = (parts.next(), parts.next(), parts.next());
                let days: u64 = days.unwrap().parse().unwrap();
                match (kind, rel) {
                    (Some("d"), Some(rel)) => t.d(days, rel),
                    (Some("f"), Some(rel)) => t.f(days, rel),
                    _ => panic!("bad fixture line: {line}"),
                };
            }
            t
        }

        /// A project with `package.json` and a populated `node_modules`.
        fn project(&mut self, rel: &str, days: u64) -> &mut Self {
            self.d(days, rel)
                .f(days, &format!("{rel}/package.json"))
                .d(days, &format!("{rel}/node_modules"))
                .f(days, &format!("{rel}/node_modules/x.js"))
        }
    }

    fn run(fs: &dyn Fs, min_age_days: u32, user_paths: Vec<PathBuf>) -> ScanReport {
        try_run(fs, min_age_days, user_paths, &AtomicBool::new(false)).unwrap()
    }

    fn try_run(
        fs: &dyn Fs,
        min_age_days: u32,
        user_paths: Vec<PathBuf>,
        cancel: &AtomicBool,
    ) -> Result<ScanReport, ScanError> {
        let protect = ProtectList::builtin(&HomeAt).unwrap().with_identities(fs);
        let roots = ResolvedRoots {
            home: h(""),
            caches: h("Library/Caches"),
            logs: h("Library/Logs"),
        };
        let ctx = ScanContext {
            fs,
            protect: &protect,
            roots: &roots,
            rule_ctx: RuleContext {
                min_age_days,
                user_paths,
                now: now(),
            },
            threads: Some(2),
        };
        scan(&[&NODE_MODULES], &ctx, cancel)
    }

    fn listed(report: &ScanReport) -> Vec<PathBuf> {
        report.items.iter().map(|i| i.path.clone()).collect()
    }

    // Acceptance 8: of two projects with package.json, 60 and 2 days old,
    // only the 60-day one's node_modules is listed. FR-007: nothing from
    // protected, hidden, Library or app-bundle folders.
    #[test]
    fn fixture_lists_only_inactive_project() {
        let t = Tree::fixture();
        let report = run(&t.fs, 30, vec![h("code")]);
        assert_eq!(listed(&report), vec![h("code/old/node_modules")]);

        let report = run(&t.fs, 30, Vec::new());
        assert_eq!(listed(&report), vec![h("code/old/node_modules")]);
        assert_eq!(report.items[0].allocated_bytes, 2 * 8 * 512);
        assert!(report.skipped.contains(&Skipped {
            path: h("Documents"),
            reason: SkipReason::Protected,
        }));
    }

