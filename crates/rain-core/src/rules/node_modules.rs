    /// Records every path read, to prove what the age check never opens.
    struct Recording<'a> {
        inner: &'a FakeFs,
        seen: std::sync::Mutex<Vec<PathBuf>>,
    }

    impl Fs for Recording<'_> {
        fn symlink_metadata(&self, p: &Path) -> io::Result<Metadata> {
            self.seen.lock().unwrap().push(p.to_path_buf());
            self.inner.symlink_metadata(p)
        }
        fn read_dir(&self, p: &Path) -> io::Result<Vec<crate::fs::DirEntryInfo>> {
            self.seen.lock().unwrap().push(p.to_path_buf());
            self.inner.read_dir(p)
        }
        fn canonicalize(&self, p: &Path) -> io::Result<PathBuf> {
            self.inner.canonicalize(p)
        }
    }

    // FR-007: the age check never looks inside a protected folder; a project
    // holding one (here the home itself) cannot be proven inactive.
    #[test]
    fn age_check_never_enters_protected_folders() {
        let mut t = Tree::new();
        t.f(90, "package.json")
            .d(90, "node_modules")
            .f(90, "node_modules/x.js")
            .d(90, "Desktop")
            .f(90, "Desktop/secret.txt");
        let fs = Recording {
            inner: &t.fs,
            seen: std::sync::Mutex::new(Vec::new()),
        };
        let report = run(&fs, 30, Vec::new());
        assert!(report.items.is_empty());
        let seen = fs.seen.lock().unwrap();
        assert!(
            !seen
                .iter()
                .any(|p| p.starts_with(h("Desktop")) && p != &h("Desktop")),
            "{seen:?}"
        );
    }

    /// Turns the cancel flag on when `trigger` is listed, and records every
    /// directory listed afterwards.
    struct CancelOn<'a> {
        inner: &'a FakeFs,
        trigger: PathBuf,
        cancel: &'a AtomicBool,
        after: std::sync::Mutex<Vec<PathBuf>>,
    }

    impl Fs for CancelOn<'_> {
        fn symlink_metadata(&self, p: &Path) -> io::Result<Metadata> {
            self.inner.symlink_metadata(p)
        }
        fn read_dir(&self, p: &Path) -> io::Result<Vec<crate::fs::DirEntryInfo>> {
            if self.cancel.load(Ordering::SeqCst) {
                self.after.lock().unwrap().push(p.to_path_buf());
            }
            if p == self.trigger {
                self.cancel.store(true, Ordering::SeqCst);
            }
            self.inner.read_dir(p)
        }
        fn canonicalize(&self, p: &Path) -> io::Result<PathBuf> {
            self.inner.canonicalize(p)
        }
    }

    // FR-011: Ctrl+C during the age check stops it at once and the scan is
    // cancelled, never reported with the project taken as active.
    #[test]
    fn age_walk_honours_cancel() {
        let mut t = Tree::new();
        t.project("p", 60)
            .d(60, "p/src")
            .d(60, "p/src/a")
            .d(60, "p/src/a/b")
            .f(60, "p/src/a/b/c.js");
        let cancel = AtomicBool::new(false);
        // `p/src` is listed first by the age walk (discovery reaches it one
        // level after `p/node_modules` is visited).
        let fs = CancelOn {
            inner: &t.fs,
            trigger: h("p/src"),
            cancel: &cancel,
            after: std::sync::Mutex::new(Vec::new()),
        };
        let result = try_run(&fs, 30, Vec::new(), &cancel);
        assert_eq!(result, Err(ScanError::Cancelled));
        let after = fs.after.lock().unwrap();
        assert!(after.is_empty(), "{after:?}");
    }

    // The age walk never enters any node_modules, so a monorepo is not
    // walked once per package.
    #[test]
    fn age_walk_skips_every_node_modules() {
        let mut t = Tree::new();
        t.project("p", 60)
            .d(60, "p/pkg")
            .d(60, "p/pkg/node_modules")
            .f(0, "p/pkg/node_modules/fresh.js");
        let fs = Recording {
            inner: &t.fs,
            seen: std::sync::Mutex::new(Vec::new()),
        };
        let report = run(&fs, 30, Vec::new());
        assert_eq!(listed(&report), vec![h("p/node_modules")]);
        let seen = fs.seen.lock().unwrap();
        assert!(
            !seen
                .iter()
                .any(|p| p.starts_with(h("p/pkg/node_modules")) && p != &h("p/pkg/node_modules")),
            "{seen:?}"
        );
    }

    // Spec criterion: a recent subproject keeps the outer project active;
    // when both are old, both node_modules are listed once each.
    #[test]
    fn nested_projects() {
        let mut t = Tree::new();
        t.project("outer", 60).project("outer/sub", 2);
        assert!(run(&t.fs, 30, Vec::new()).items.is_empty());

        let mut t = Tree::new();
        t.project("outer", 60).project("outer/sub", 60);
        let report = run(&t.fs, 30, Vec::new());
        assert_eq!(
            listed(&report),
            vec![h("outer/node_modules"), h("outer/sub/node_modules")]
        );
        assert_eq!(report.items[0].file_count, 1);
        assert_eq!(report.items[1].file_count, 1);
    }

    // A project too large to check within the entry budget counts as active.
    #[test]
    fn age_walk_over_budget_is_active() {
        let mut t = Tree::new();
        t.project("p", 60).f(60, "p/a.js").f(60, "p/b.js");
        let protect = ProtectList::builtin(&HomeAt).unwrap();
        let cancel = AtomicBool::new(false);
        let path = h("p/node_modules");
        let meta = t.fs.symlink_metadata(&path).unwrap();
        let entry = EntryInfo {
            path: &path,
            meta: &meta,
            protect: &protect,
            cancel: &cancel,
        };
        let project = h("p");
        assert!(matches!(
            newest_mtime(&entry, &project, &t.fs, 10),
            Age::Newest(_)
        ));
        assert_eq!(newest_mtime(&entry, &project, &t.fs, 2), Age::Unknown);
    }

    // FR-009: --path roots replace the home; without them the home is used.
    #[test]
    fn roots_are_user_paths_or_home() {
        let ctx = |user_paths| RuleContext {
            min_age_days: 30,
            user_paths,
            now: now(),
        };
        assert_eq!(
            NODE_MODULES.roots(&ctx(Vec::new())),
            vec![RootedPath::Under(Root::Home, "")]
        );
        assert_eq!(
            NODE_MODULES.roots(&ctx(vec![h("a"), h("b")])),
            vec![RootedPath::User(h("a")), RootedPath::User(h("b"))]
        );
    }

    // FR-013: the display name is a catalogue key, present in every locale.
    #[test]
    fn name_key_exists_in_every_locale() {
        let key = MessageKey::RuleDevNodeModules;
        assert_eq!(key.as_str(), NODE_MODULES.meta().name_key);
        for locale in Locale::ALL {
            let catalog = Catalog::for_locale(*locale).unwrap();
            assert!(catalog.try_get(key).is_some(), "{}", locale.tag());
        }
    }
