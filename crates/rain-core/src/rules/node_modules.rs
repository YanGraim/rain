//! `proj.node-modules`: `node_modules` of inactive JavaScript projects.

use crate::fs::Fs;
use crate::model::{Category, Risk, RuleId};
use crate::rule::{EntryInfo, FileRule, RootedPath, Rule, RuleContext, RuleKind, RuleMeta, Visit};
use rain_platform::{Os, Root};
use std::path::{Path, PathBuf};
use std::sync::atomic::Ordering;
use std::time::{Duration, SystemTime};

pub struct NodeModules {
    meta: RuleMeta,
}

pub static NODE_MODULES: NodeModules = NodeModules {
    meta: RuleMeta {
        id: RuleId::new("proj.node-modules"),
        category: Category::Projects,
        risk: Risk::Medium,
        name_key: "rule.proj.node-modules",
        consequence_key: "rule.proj.node-modules.consequence",
        default_selected: true,
        requires_app_closed: None,
        os: &[Os::Macos],
    },
};

impl Rule for NodeModules {
    fn meta(&self) -> &RuleMeta {
        &self.meta
    }
    fn kind(&self) -> RuleKind<'_> {
        RuleKind::Files(self)
    }
}

const NODE_MODULES_DIR: &str = "node_modules";
const MANIFEST: &str = "package.json";
const SECONDS_PER_DAY: u64 = 86_400;

impl FileRule for NodeModules {
    /// FR-009: the `--path` roots, or the home when there are none.
    fn roots(&self, ctx: &RuleContext) -> Vec<RootedPath> {
        if ctx.user_paths.is_empty() {
            vec![RootedPath::Under(Root::Home, "")]
        } else {
            ctx.user_paths
                .iter()
                .cloned()
                .map(RootedPath::User)
                .collect()
        }
    }

    fn visit(&self, entry: &EntryInfo, depth: usize, ctx: &RuleContext, fs: &dyn Fs) -> Visit {
        if !entry.meta.is_dir {
            return Visit::Skip;
        }
        if depth == 0 {
            // A root inside a node_modules could only offer nested ones.
            let inside = entry
                .path
                .components()
                .any(|c| c.as_os_str() == NODE_MODULES_DIR);
            return if inside { Visit::Skip } else { Visit::Descend };
        }
        let Some(name) = entry.path.file_name() else {
            return Visit::Skip;
        };
        if never_entered(name.as_encoded_bytes()) {
            return Visit::Skip;
        }
        if name != NODE_MODULES_DIR {
            return Visit::Descend;
        }
        // Never descend into a node_modules: nested ones are already inside
        // the size of the outer one.
        match entry.path.parent() {
            Some(project) if has_manifest(fs, project) && is_inactive(entry, project, ctx, fs) => {
                Visit::Candidate
            }
            _ => Visit::Skip,
        }
    }
}

/// Hidden folders, `Library` and app bundles hold tool and app internals,
/// whose node_modules are not projects of the user.
fn never_entered(name: &[u8]) -> bool {
    name.starts_with(b".") || name == b"Library" || name.ends_with(b".app")
}

/// A regular `package.json` beside the node_modules (not a link, not a folder).
fn has_manifest(fs: &dyn Fs, project: &Path) -> bool {
    fs.symlink_metadata(&project.join(MANIFEST))
        .is_ok_and(|m| !m.is_dir && !m.is_symlink)
}

/// No entry of the project outside `entry` (its node_modules) was modified
/// in the last `min_age_days`. Anything that cannot be checked (unreadable,
/// protected, future mtime) counts as active: a wrong answer must cost a
/// candidate, never add one.
/// A cancelled check is not a candidate either; the planner then sees the
/// flag and drops the whole scan (FR-011).
fn is_inactive(entry: &EntryInfo, project: &Path, ctx: &RuleContext, fs: &dyn Fs) -> bool {
    let Age::Newest(newest) = newest_mtime(entry, project, fs, AGE_WALK_BUDGET) else {
        return false;
    };
    let min_age = Duration::from_secs(u64::from(ctx.min_age_days) * SECONDS_PER_DAY);
    ctx.now
        .duration_since(newest)
        .is_ok_and(|age| age >= min_age)
}

/// Most entries the age check reads per project; beyond it the project is
/// taken as active, so one huge tree cannot stall discovery.
const AGE_WALK_BUDGET: usize = 200_000;

/// Outcome of the age check.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Age {
    Newest(SystemTime),
    /// Could not be proven (read error, protected folder, over budget).
    Unknown,
    Cancelled,
}

/// Newest mtime in `project`, outside every node_modules (their content
/// is dependencies, not project activity). Never follows symlinks
/// (FR-005), never leaves the volume (FR-006) and never enters a protected
/// folder (FR-007); meeting a protected folder, a read error or more than
/// `budget` entries gives [`Age::Unknown`]. Checks the cancel flag before
/// every listing (FR-011).
fn newest_mtime(entry: &EntryInfo, project: &Path, fs: &dyn Fs, budget: usize) -> Age {
    let dev = entry.meta.dev;
    let Ok(root) = fs.symlink_metadata(project) else {
        return Age::Unknown;
    };
    let mut newest = root.mtime;
    let mut read = 0usize;
    let mut pending: Vec<PathBuf> = vec![project.to_path_buf()];
    while let Some(dir) = pending.pop() {
        if entry.cancel.load(Ordering::SeqCst) {
            return Age::Cancelled;
        }
        let Ok(children) = fs.read_dir(&dir) else {
            return Age::Unknown;
        };
        for child in children {
            if child
                .path
                .file_name()
                .is_some_and(|n| n == NODE_MODULES_DIR)
            {
                continue;
            }
            read += 1;
            if read > budget {
                return Age::Unknown;
            }
            let Ok(meta) = fs.symlink_metadata(&child.path) else {
                return Age::Unknown;
            };
            newest = newest.max(meta.mtime);
            if !meta.is_dir || meta.is_symlink || meta.dev != dev {
                continue;
            }
            if entry.protect.is_protected_entry(&child.path, &meta) {
                return Age::Unknown;
            }
            pending.push(child.path);
        }
    }
    Age::Newest(newest)
}

