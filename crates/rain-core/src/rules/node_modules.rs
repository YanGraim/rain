    /// Records every path read, to prove what the age check never opens.
    struct Recording<'a> {
        inner: &'a FakeFs,
        seen: std::sync::Mutex<Vec<PathBuf>>,
    }

    impl Fs for Recording<'_> {
        fn symlink_metadata(&self, p: &Path) -> io::Result<Metadata> {
            self.seen.lock().unwrap().push(p.to_path_buf());
            self.inner.symlink_metadata(p)
        }
        fn read_dir(&self, p: &Path) -> io::Result<Vec<crate::fs::DirEntryInfo>> {
            self.seen.lock().unwrap().push(p.to_path_buf());
            self.inner.read_dir(p)
        }
        fn canonicalize(&self, p: &Path) -> io::Result<PathBuf> {
            self.inner.canonicalize(p)
        }
    }

    // FR-007: the age check never looks inside a protected folder; a project
    // holding one (here the home itself) cannot be proven inactive.
    #[test]
    fn age_check_never_enters_protected_folders() {
        let mut t = Tree::new();
        t.f(90, "package.json")
            .d(90, "node_modules")
            .f(90, "node_modules/x.js")
            .d(90, "Desktop")
            .f(90, "Desktop/secret.txt");
        let fs = Recording {
            inner: &t.fs,
            seen: std::sync::Mutex::new(Vec::new()),
        };
        let report = run(&fs, 30, Vec::new());
        assert!(report.items.is_empty());
        let seen = fs.seen.lock().unwrap();
        assert!(
            !seen
                .iter()
                .any(|p| p.starts_with(h("Desktop")) && p != &h("Desktop")),
            "{seen:?}"
        );
    }

    /// Turns the cancel flag on when `trigger` is listed, and records every
    /// directory listed afterwards.
    struct CancelOn<'a> {
        inner: &'a FakeFs,
        trigger: PathBuf,
        cancel: &'a AtomicBool,
        after: std::sync::Mutex<Vec<PathBuf>>,
    }

    impl Fs for CancelOn<'_> {
        fn symlink_metadata(&self, p: &Path) -> io::Result<Metadata> {
            self.inner.symlink_metadata(p)
        }
        fn read_dir(&self, p: &Path) -> io::Result<Vec<crate::fs::DirEntryInfo>> {
            if self.cancel.load(Ordering::SeqCst) {
                self.after.lock().unwrap().push(p.to_path_buf());
            }
            if p == self.trigger {
                self.cancel.store(true, Ordering::SeqCst);
            }
            self.inner.read_dir(p)
        }
        fn canonicalize(&self, p: &Path) -> io::Result<PathBuf> {
            self.inner.canonicalize(p)
        }
    }

    // FR-011: Ctrl+C during the age check stops it at once and the scan is
    // cancelled, never reported with the project taken as active.
    #[test]
    fn age_walk_honours_cancel() {
        let mut t = Tree::new();
        t.project("p", 60)
            .d(60, "p/src")
            .d(60, "p/src/a")
            .d(60, "p/src/a/b")
            .f(60, "p/src/a/b/c.js");
        let cancel = AtomicBool::new(false);
        // `p/src` is listed first by the age walk (discovery reaches it one
        // level after `p/node_modules` is visited).
        let fs = CancelOn {
            inner: &t.fs,
            trigger: h("p/src"),
            cancel: &cancel,
            after: std::sync::Mutex::new(Vec::new()),
        };
        let result = try_run(&fs, 30, Vec::new(), &cancel);
        assert_eq!(result, Err(ScanError::Cancelled));
        let after = fs.after.lock().unwrap();
        assert!(after.is_empty(), "{after:?}");
    }

